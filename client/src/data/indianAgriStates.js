// Helper: Get all zones flattened
export const getAllOperationalZones = () => {
  return ALL_INDIAN_STATES_AND_HUBS.flatMap((stateObj) =>
    stateObj.zones.map((zone) => ({
      ...zone,
      state: stateObj.state,
      stateHindi: stateObj.stateHindi
    }))
  );
};

// Helper: Find zone by id
export const findZoneById = (zoneId) => {
  for (const s of ALL_INDIAN_STATES_AND_HUBS) {
    const found = s.zones.find((z) => z.id === zoneId);
    if (found) {
      return { ...found, state: s.state, stateHindi: s.stateHindi };
    }
  }
  // Fallback to Zone North UP
  return {
    ...ALL_INDIAN_STATES_AND_HUBS[25].zones[0],
    state: 'Uttar Pradesh',
    stateHindi: 'उत्तर प्रदेश'
  };
};
